select 
   DOCUMENTO_FATURA.CODIGO_DOCFAT CODIGO_PEDIDO,
   DOCUMENTO_FATURA.CLIENTE_DOCFAT CODIGO_CLIENTE,
   CLIENTE.RAZAOSOCIAL_PESSOA RAZAO_SOCIAL,
   case when CLIENTE.GRUPO_PESSOA = 0 then CLIENTE.RAZAOSOCIAL_PESSOA else CLIENTE.GRUPO_PESSOA || ' - ' || GRUPO_CLIENTE.DESCRICAO_GRUPO end as GRUPO_CLIENTE,
   COMISSAO_CON.PESSOA_DOCCOM AS CODIGO_CONSULTOR,
   COALESCE(COMISSAO_CON.PESSOA_DOCCOM || ' - ' || PESSOA_CON.RAZAOSOCIAL_PESSOA, 'INDEFINIDO') AS CONSULTOR,
   COALESCE(COMISSAO_SUP.PESSOA_DOCCOM || ' - ' || PESSOA_SUP.RAZAOSOCIAL_PESSOA, 'INDEFINIDO') AS SUPERVISOR,
   cast (DOCUMENTO_FATURA.DTEMISSAO_DOCFAT as date) DATA_EMISSAO_PEDIDO,
   EXTRACT(DAY FROM DOCUMENTO_FATURA.DTEMISSAO_DOCFAT) DIA,
   EXTRACT(MONTH FROM DOCUMENTO_FATURA.DTEMISSAO_DOCFAT) MES,
   EXTRACT(YEAR FROM DOCUMENTO_FATURA.DTEMISSAO_DOCFAT) ANO,
   (CURRENT_DATE - cast(DOCUMENTO_FATURA.DTEMISSAO_DOCFAT as date)) NIVEL_DE_SERVICO,
   cast(DOCUMENTO_PEDIDO.DTPREVISAOFATURAMENTO_DOCPED as date) DT_PREVISAO_FATURAMENTO,
   case trim(DOCUMENTO_FATURA.ENTREGARMERCADORIA_DOCFAT)
     when 'S' then 'ENTREGA'
     when 'N' then 'RETIRA'
     else 'RETIRA'
   end as TIPO_ENTREGA,
   DOCUMENTO_ITEM_DETALHE.VLRBRUTOLIQUIDO_DOCITEMDET VALOR_EMITIDO,
   DOCUMENTO_ITEM_DETALHE.QTDECHAPAS_DOCITEMDET QUANTIDADE_EMITIDA,
   (iif(coalesce(ITEM_DETALHE.PESOBRUTO_ITEM_DETALHE, 0) <> 0, ITEM_DETALHE.PESOBRUTO_ITEM_DETALHE, ITEM.PESOBRUTO_ITEM) * DOCUMENTO_ITEM_DETALHE.QTDECHAPAS_DOCITEMDET) PESO_EMITIDO,
   (iif(coalesce(ITEM_DETALHE.VOLUMEM3_ITEM_DETALHE, 0) <> 0, ITEM_DETALHE.VOLUMEM3_ITEM_DETALHE, iif(coalesce(ITEM.VOLUMEM3_ITEM, 0) < 10, coalesce(ITEM.VOLUMEM3_ITEM, 0), 0)) * DOCUMENTO_ITEM_DETALHE.QTDECHAPAS_DOCITEMDET) VOLUME_M3_EMITIDO,
   UF.SIGLA_UF UF,
   case UF.REGIAO_UF
     when 0 then 'INDEFINIDA'
     when 1 then 'CENTRO-OESTE'
     when 2 then 'NORDESTE'
     when 3 then 'NORTE'
     when 4 then 'SUL'
     when 5 then 'SUDESTE'
     when 6 then 'EXTERIOR'
   end as REGIAO_UF,
   REGIAO.descricao_regiao MICRO_REGIAO,
   CIDADE.descricao_cidade CIDADE,  
   CLASSIFICACAO.DESCRICAO_CLASSIF AS CLASSIFICACAO,
   ORIGEM.DESCRICAO_ORIGEM ORIGEM,
   ORGAO.DESCRICAO_ORGAO ORGAO,
   STATUS.DESCRICAO_STATUS STATUS,
   ITEM.CODIGO_ITEM AS CODIGO_ITEM,
   ITEM.DESCRICAO_ITEM AS DESCRICAO_ITEM,
   COR.CODIGO_COR || ' - ' || COR.DESCRICAO_COR AS COR, 
   ITEM.GRUPO_ITEM || ' - ' || GRUPO_ITEM.DESCRICAO_GRUPO GRUPO_ITEM,
   ITEM.SUBGRUPO_ITEM || ' - ' || SUBGRUPO.DESCRICAO_SUBGRUPO SUBGRUPO,
   ITEM.TIPOPRODUTO_ITEM || ' - ' || TIPOPRODUTO.DESCRICAO_TIPOPROD TIPO,
   ITEM.COLECAO_ITEM || ' - ' || COLECAO.DESCRICAO_COLECAO COLECAO,
   ITEM.LINHA_ITEM || ' - ' || LINHA.DESCRICAO_LINHA LINHA,
   DOCUMENTO_ITEM_DETALHE.VLRUNITARIOBRUTO_DOCITEMDET,
   DOCUMENTO_ITEM_DETALHE.VLRUNITARIOLIQUIDO_DOCITEMDET,
   DOCUMENTO_ITEM_DETALHE.VLRBRUTOLIQUIDO_DOCITEMDET / DOCUMENTO_ITEM_DETALHE.QTDECHAPAS_DOCITEMDET VLR_UNIT_BRULIQ,
   DOCUMENTO_FATURA.VLRLIQUIDO_DOCFAT
 from DOCUMENTO_FATURA
 inner join DOCUMENTO_ITEM         on (DOCUMENTO_ITEM.DOCUMENTO_DOCITEM              = DOCUMENTO_FATURA.CODIGO_DOCFAT) 
 inner join DOCUMENTO_ITEM_DETALHE on (DOCUMENTO_ITEM_DETALHE.AUTOINCITEM_DOCITEMDET = DOCUMENTO_ITEM.AUTOINC_DOCITEM) 
 left  join DOCUMENTO_PEDIDO       on (DOCUMENTO_PEDIDO.DOCUMENTO_DOCPED             = DOCUMENTO_FATURA.CODIGO_DOCFAT) 
 left  join DOCUMENTO_FISCAL       on (DOCUMENTO_FISCAL.DOCUMENTO_DOCFISCAL          = DOCUMENTO_FATURA.CODIGO_DOCFAT) 
 inner join ORGAO                  on (ORGAO.CODIGO_ORGAO                            = DOCUMENTO_FATURA.ORGAO_DOCFAT) 
 inner join ORIGEM                 on (ORIGEM.CODIGO_ORIGEM                          = DOCUMENTO_FATURA.ORIGEM_DOCFAT) 
 inner join CLASSIFICACAO          on (CLASSIFICACAO.CODIGO_CLASSIF                  = DOCUMENTO_FATURA.CLASSIFICACAO_DOCFAT) 
 inner join STATUS                 on (STATUS.CODIGO_STATUS                          = DOCUMENTO_FATURA.STATUS_DOCFAT) 
 left  join PESSOA         CLIENTE on (CLIENTE.CODIGO_PESSOA                         = DOCUMENTO_FATURA.CLIENTE_DOCFAT)
 inner join GRUPO   GRUPO_CLIENTE  on (GRUPO_CLIENTE.CODIGO_GRUPO                    = CLIENTE.GRUPO_PESSOA)           
 left  join DOCUMENTO_COMISSAO COMISSAO_CON on (COMISSAO_CON.DOCUMENTO_DOCCOM         = DOCUMENTO_FATURA.CODIGO_DOCFAT and COMISSAO_CON.TIPOPESSOA_DOCCOM = 0 and COMISSAO_CON.PRINCIPAL_DOCCOM = 'S') 
 left  join PESSOA             PESSOA_CON   on (PESSOA_CON.CODIGO_PESSOA             = COMISSAO_CON.PESSOA_DOCCOM) 
 left  join DOCUMENTO_COMISSAO COMISSAO_SUP on (COMISSAO_SUP.DOCUMENTO_DOCCOM         = DOCUMENTO_FATURA.CODIGO_DOCFAT and COMISSAO_SUP.TIPOPESSOA_DOCCOM = 1 and COMISSAO_SUP.PRINCIPAL_DOCCOM = 'S') 
 left  join PESSOA             PESSOA_SUP   on (PESSOA_SUP.CODIGO_PESSOA             = COMISSAO_SUP.PESSOA_DOCCOM) 
 left  join PESSOA_ENDERECO        on (PESSOA_ENDERECO.AUTOINC_PESSOA_END            = DOCUMENTO_FATURA.LOCALENTREGA_DOCFAT) 
 left  join REGIAO                 on (REGIAO.CODIGO_REGIAO                          = PESSOA_ENDERECO.REGIAO_PESSOA_END) 
 left  join CIDADE                 on (CIDADE.CODIGO_CIDADE                          = PESSOA_ENDERECO.CIDADE_PESSOA_END) 
 left  join UF                     on (UF.CODIGO_UF                                  = CIDADE.UF_CIDADE)  
 inner join ITEM                   on (ITEM.CODIGO_ITEM                              = DOCUMENTO_ITEM.ITEM_DOCITEM) 
 inner join GRUPO   GRUPO_ITEM     on (GRUPO_ITEM.CODIGO_GRUPO                       = ITEM.GRUPO_ITEM)           
 inner join SUBGRUPO               on (SUBGRUPO.CODIGO_SUBGRUPO                      = ITEM.SUBGRUPO_ITEM)        
 inner join TIPOPRODUTO            on (TIPOPRODUTO.CODIGO_TIPOPROD                   = ITEM.TIPOPRODUTO_ITEM)            
 inner join COLECAO                on (COLECAO.CODIGO_COLECAO                        = ITEM.COLECAO_ITEM)         
 inner join LINHA                  on (LINHA.CODIGO_LINHA                            = ITEM.LINHA_ITEM)           
 left  join ITEM_DETALHE           on (ITEM_DETALHE.AUTOINC_ITEM_DETALHE             = DOCUMENTO_ITEM_DETALHE.AUTOINCITEMDETALHE_DOCITEMDET)
 left  join COR                    on (COR.CODIGO_COR                                = DOCUMENTO_ITEM_DETALHE.COR_DOCITEMDET) 
 where (DOCUMENTO_FATURA.DTEMISSAO_DOCFAT >= '2025-01-01')
   and (CLIENTE.GRUPO_PESSOA <> 1603)
   and (DOCUMENTO_FATURA.TIPO_DOCFAT                 = 1)
   and (DOCUMENTO_FATURA.OPCAO_DOCFAT                = 1)
   and (DOCUMENTO_ITEM.AUTOINC_DOCITEM               = DOCUMENTO_ITEM.COMPOSICAOITEM_DOCITEM)
   and (DOCUMENTO_ITEM.TIPO_DOCITEM                  in (1,4))
