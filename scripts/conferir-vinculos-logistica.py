"""Bounded aggregate reconciliation of the anonymized local Firebird copy."""
import datetime
import json
import os
from pathlib import Path
import sys
import time
import fdb

ROOT = Path(__file__).resolve().parents[1]


def main():
    sys.stdout.reconfigure(encoding='utf-8')
    database = os.environ.get('FIREBIRD_DATABASE')
    if not database or os.environ.get('FIREBIRD_HOST', 'localhost') not in ['localhost', '127.0.0.1']:
        raise SystemExit('Configure a cópia Firebird local no ambiente.')
    fdb.load_api(r'C:\Program Files\Firebird\Firebird_5_0\fbclient.dll')
    connection = fdb.connect(host='localhost', port=int(os.environ.get('FIREBIRD_PORT', '3050')),
                             database=database, user=os.environ['FIREBIRD_USER'],
                             password=os.environ['FIREBIRD_PASSWORD'], charset='ISO8859_1')
    tpb = fdb.TPB(); tpb.access_mode = fdb.isc_tpb_read; tpb.isolation_level = fdb.isc_tpb_concurrency
    connection.begin(tpb=tpb.render())
    report = {'source': 'local-anonymized-copy', 'databaseFile': database, 'readOnly': True,
              'inspectedAt': datetime.datetime.now(datetime.timezone.utc).isoformat(), 'queries': {}}
    queries = {
        'foreignKeys': """SELECT TRIM(c.RDB$RELATION_NAME) AS SOURCE_TABLE, TRIM(s.RDB$FIELD_NAME) AS SOURCE_FIELD,
            TRIM(p.RDB$RELATION_NAME) AS TARGET_TABLE, TRIM(ps.RDB$FIELD_NAME) AS TARGET_FIELD
            FROM RDB$RELATION_CONSTRAINTS c JOIN RDB$REF_CONSTRAINTS r ON r.RDB$CONSTRAINT_NAME=c.RDB$CONSTRAINT_NAME
            JOIN RDB$RELATION_CONSTRAINTS p ON p.RDB$CONSTRAINT_NAME=r.RDB$CONST_NAME_UQ
            JOIN RDB$INDEX_SEGMENTS s ON s.RDB$INDEX_NAME=c.RDB$INDEX_NAME
            JOIN RDB$INDEX_SEGMENTS ps ON ps.RDB$INDEX_NAME=p.RDB$INDEX_NAME AND ps.RDB$FIELD_POSITION=s.RDB$FIELD_POSITION
            WHERE c.RDB$RELATION_NAME IN ('CARGA_ITENS','CARGA_DOCUMENTOS','DOCUMENTO_ITEM_DETALHE','DOCUMENTO_ENTREGA')""",
        'recentLoadsCoverage': """SELECT COUNT(*) AS LOADS, MIN(DTEMISSAO_CARGA) AS MIN_DATE, MAX(DTEMISSAO_CARGA) AS MAX_DATE,
            COUNT(DATAINICIO_SEPARACAO_CARGA) AS SEPARATION_STARTED, COUNT(DATA_CONFERENCIA_CARGA) AS CONFERENCE_FINISHED,
            COUNT(DATAHORALIB_SAIDA_CARGA) AS EXIT_RELEASED, COUNT(DATAHORAFECHAMENTO_CARGA) AS CLOSED,
            COUNT(FRETECOMBINADO_CARGA) AS FREIGHT_RECORDED
            FROM CARGA WHERE DTEMISSAO_CARGA >= '2026-01-01'""",
        'recentDocumentTypes': """SELECT TIPO_DOCFAT AS DOCUMENT_TYPE, ENTREGA_DOCFAT AS DELIVERY_FLAG, COUNT(*) AS DOCUMENTS,
            COUNT(DATAENTREGA_DOCFAT) AS DELIVERY_DATE_RECORDED, COUNT(DTSAIDA_DOCFAT) AS EXIT_DATE_RECORDED
            FROM DOCUMENTO_FATURA WHERE DTEMISSAO_DOCFAT >= '2026-01-01'
            GROUP BY TIPO_DOCFAT, ENTREGA_DOCFAT""",
        'openItemBalance': """SELECT COUNT(*) AS ITEMS, COUNT(DISTINCT d.CODIGO_DOCFAT) AS ORDERS,
            SUM(i.QTDEABERTA_DOCITEMDET) AS OPEN_QUANTITY, SUM(i.QTDECARGA_DOCITEMDET) AS LOAD_QUANTITY,
            SUM(i.QTDECARGAFAT_DOCITEMDET) AS BILLED_LOAD_QUANTITY, SUM(i.QTDEFATURADO_DOCITEMDET) AS BILLED_QUANTITY,
            SUM(i.QTDECANCELADO_DOCITEMDET) AS CANCELLED_QUANTITY,
            SUM(CASE WHEN i.QTDECARGA_DOCITEMDET > 0 AND i.QTDEABERTA_DOCITEMDET > i.QTDECARGA_DOCITEMDET THEN 1 ELSE 0 END) AS PARTIAL_LOAD_ITEMS,
            SUM(CASE WHEN i.QTDEABERTA_DOCITEMDET > 0 AND COALESCE(i.QTDECARGA_DOCITEMDET,0)=0 THEN 1 ELSE 0 END) AS ITEMS_WITHOUT_LOAD
            FROM DOCUMENTO_FATURA d JOIN DOCUMENTO_ITEM di ON di.DOCUMENTO_DOCITEM=d.CODIGO_DOCFAT
            JOIN DOCUMENTO_ITEM_DETALHE i ON i.AUTOINCITEM_DOCITEMDET=di.AUTOINC_DOCITEM
            WHERE d.DTEMISSAO_DOCFAT >= '2026-01-01' AND d.TIPO_DOCFAT=1 AND d.OPCAO_DOCFAT=1 AND d.ENTREGA_DOCFAT='N'
            AND i.QTDEABERTA_DOCITEMDET>0 AND di.AUTOINC_DOCITEM=di.COMPOSICAOITEM_DOCITEM AND di.TIPO_DOCITEM IN (1,4)""",
        'sampleAllocationReconciliation': """WITH sample AS (
            SELECT FIRST 5000 i.AUTOINC_DOCITEMDET, i.QTDEABERTA_DOCITEMDET, i.QTDECARGA_DOCITEMDET, i.QTDECARGAFAT_DOCITEMDET
            FROM DOCUMENTO_ITEM_DETALHE i JOIN DOCUMENTO_FATURA d ON d.CODIGO_DOCFAT=i.DOCUMENTO_DOCITEMDET
            WHERE d.DTEMISSAO_DOCFAT >= '2026-01-01' AND d.TIPO_DOCFAT=1 AND d.ENTREGA_DOCFAT='N' AND i.QTDEABERTA_DOCITEMDET>0
            ORDER BY i.AUTOINC_DOCITEMDET DESC), balances AS (
            SELECT s.AUTOINC_DOCITEMDET, s.QTDEABERTA_DOCITEMDET, s.QTDECARGA_DOCITEMDET, s.QTDECARGAFAT_DOCITEMDET,
                COUNT(ci.AUTOINC_CARITE) AS ALLOCATIONS, COUNT(DISTINCT cd.CARGA_CARDOC) AS LOADS,
                COALESCE(SUM(ci.QTDEABERTA_CARITE),0) AS ALLOCATED_OPEN,
                COALESCE(SUM(ci.QTDECHAPAS_CARITE),0) AS ALLOCATED_TOTAL,
                COALESCE(SUM(ci.QTDEFATURADO_CARITE),0) AS ALLOCATED_BILLED
            FROM sample s LEFT JOIN CARGA_ITENS ci ON ci.AUTOINCITEMDETDOC_CARITE=s.AUTOINC_DOCITEMDET
            LEFT JOIN CARGA_DOCUMENTOS cd ON cd.AUTOINC_CARDOC=ci.AUTOINCCARDOC_CARITE
            GROUP BY s.AUTOINC_DOCITEMDET,s.QTDEABERTA_DOCITEMDET,s.QTDECARGA_DOCITEMDET,s.QTDECARGAFAT_DOCITEMDET)
            SELECT COUNT(*) AS ITEMS, SUM(CASE WHEN LOADS>1 THEN 1 ELSE 0 END) AS ITEMS_MULTIPLE_LOADS,
                SUM(CASE WHEN ALLOCATED_OPEN>QTDEABERTA_DOCITEMDET THEN 1 ELSE 0 END) AS OVERALLOCATED,
                SUM(CASE WHEN ABS(ALLOCATED_OPEN-COALESCE(QTDECARGA_DOCITEMDET,0))>0.000001 THEN 1 ELSE 0 END) AS OPEN_VS_LOAD_FIELD_DIFFERENCES,
                SUM(CASE WHEN ABS(ALLOCATED_OPEN-(COALESCE(QTDECARGA_DOCITEMDET,0)-COALESCE(QTDECARGAFAT_DOCITEMDET,0)))>0.000001 THEN 1 ELSE 0 END) AS OPEN_VS_NET_LOAD_DIFFERENCES,
                SUM(ALLOCATED_OPEN) AS ALLOCATED_OPEN_TOTAL, SUM(QTDECARGA_DOCITEMDET) AS LOAD_FIELD_TOTAL,
                SUM(QTDECARGAFAT_DOCITEMDET) AS BILLED_LOAD_FIELD_TOTAL FROM balances""",
    }
    # Same cohort and composition filters as the native logistics publication.
    population = """SELECT d.CODIGO_DOCFAT AS ORDER_ID, d.EMPRESA_DOCFAT AS COMPANY_ID,
        i.AUTOINC_DOCITEMDET AS ITEM_ID, i.QTDEABERTA_DOCITEMDET AS OPEN_QUANTITY,
        COALESCE(SUM(ci.QTDEABERTA_CARITE),0) AS ALLOCATED_QUANTITY,
        TRUNC(i.VLRBRUTOLIQUIDO_DOCITEMDET / NULLIF(i.QTDECHAPAS_DOCITEMDET,0),6)*i.QTDEABERTA_DOCITEMDET AS OPEN_VALUE
        FROM DOCUMENTO_FATURA d JOIN DOCUMENTO_ITEM di ON di.DOCUMENTO_DOCITEM=d.CODIGO_DOCFAT
        JOIN DOCUMENTO_ITEM_DETALHE i ON i.AUTOINCITEM_DOCITEMDET=di.AUTOINC_DOCITEM
        LEFT JOIN CARGA_ITENS ci ON ci.AUTOINCITEMDETDOC_CARITE=i.AUTOINC_DOCITEMDET
        WHERE d.DTEMISSAO_DOCFAT>='2026-01-01' AND d.DTEMISSAO_DOCFAT<'2026-10-01'
        AND d.TIPO_DOCFAT=1 AND d.OPCAO_DOCFAT=1 AND d.ENTREGA_DOCFAT='N'
        AND di.AUTOINC_DOCITEM=di.COMPOSICAOITEM_DOCITEM AND di.TIPO_DOCITEM IN (1,4) AND i.QTDEABERTA_DOCITEMDET>0
        GROUP BY d.CODIGO_DOCFAT,d.EMPRESA_DOCFAT,i.AUTOINC_DOCITEMDET,i.QTDEABERTA_DOCITEMDET,
        i.VLRBRUTOLIQUIDO_DOCITEMDET,i.QTDECHAPAS_DOCITEMDET"""
    queries['publicationCohort'] = "WITH items AS (" + population + """), orders AS (
        SELECT ORDER_ID, SUM(OPEN_QUANTITY) AS OPEN_QUANTITY, SUM(ALLOCATED_QUANTITY) AS ALLOCATED_QUANTITY FROM items GROUP BY ORDER_ID)
        SELECT COUNT(*) AS ORDERS,
        SUM(CASE WHEN ALLOCATED_QUANTITY=0 THEN 1 ELSE 0 END) AS ORDERS_NONE,
        SUM(CASE WHEN ALLOCATED_QUANTITY>0 AND ALLOCATED_QUANTITY<OPEN_QUANTITY THEN 1 ELSE 0 END) AS ORDERS_PARTIAL,
        SUM(CASE WHEN ALLOCATED_QUANTITY=OPEN_QUANTITY THEN 1 ELSE 0 END) AS ORDERS_FULL,
        SUM(OPEN_QUANTITY) AS OPEN_QUANTITY, SUM(ALLOCATED_QUANTITY) AS ALLOCATED_QUANTITY,
        SUM(OPEN_QUANTITY-ALLOCATED_QUANTITY) AS FREE_QUANTITY,
        (SELECT SUM(OPEN_VALUE) FROM items) AS OPEN_VALUE,
        (SELECT COUNT(*) FROM items WHERE OPEN_VALUE IS NULL) AS UNPRICED_ITEMS FROM orders"""
    queries['publicationCompanies'] = "WITH items AS (" + population + """ ) SELECT COMPANY_ID, COUNT(*) AS ITEMS,
        COUNT(DISTINCT ORDER_ID) AS ORDERS, SUM(OPEN_QUANTITY) AS OPEN_QUANTITY, SUM(ALLOCATED_QUANTITY) AS ALLOCATED_QUANTITY
        FROM items GROUP BY COMPANY_ID"""
    try:
        for name, sql in queries.items():
            start = time.monotonic(); cursor = connection.cursor(); cursor.execute(sql)
            columns = [x[0] for x in cursor.description]
            rows = [dict(zip(columns, row)) for row in cursor.fetchall()]
            report['queries'][name] = {'seconds': round(time.monotonic()-start,3), 'rows': rows}
            print(name + ': ' + json.dumps(report['queries'][name], default=str, ensure_ascii=False), flush=True)
        (ROOT/'.local/logistica-vinculos-auditoria.json').write_text(json.dumps(report,indent=2,default=str,ensure_ascii=False),encoding='utf-8')
    finally:
        connection.rollback(); connection.close()


if __name__ == '__main__':
    main()
