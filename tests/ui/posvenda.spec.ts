import {test,expect} from '@playwright/test'
test.use({actionTimeout:15000})

test('real aftersales publication powers open and issued assistance, sale cancellations and returns',async({page})=>{
 test.setTimeout(180_000)
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const settled=async()=>page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{})))})
 await page.goto('http://127.0.0.1:3002/assistencias')
 await expect(page.getByRole('heading',{name:'Assistências',exact:true})).toBeVisible()
 await expect(page.locator('[data-metric-id="posvenda.documents"] strong')).not.toHaveText('0',{timeout:60_000})
 await expect(page.locator('[data-metric-id="posvenda.documents"]')).toContainText('Assistências em aberto')
 await expect(page.locator('[data-series-id^="posvenda."] canvas')).toHaveCount(7,{timeout:30_000})
 await expect(page.getByRole('heading',{name:'Análise por dimensão',exact:true})).toBeVisible()
 await expect(page.getByRole('heading',{name:'Cronograma de previsão das assistências',exact:true})).toBeVisible()
 const grain=page.getByRole('group',{name:'Granularidade da evolução'})
 await grain.getByRole('button',{name:'Semanas',exact:true}).click()
 await expect(page.locator('[data-series-id="posvenda.monthly"]')).toContainText('Saldo por semana de emissão')
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 await grain.getByRole('button',{name:'Dias',exact:true}).click()
 await expect(page.locator('[data-series-id="posvenda.monthly"]')).toContainText('Saldo por dia de emissão')
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 await grain.getByRole('button',{name:'Meses',exact:true}).click()
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 const dimensions=page.getByRole('navigation',{name:'Dimensões de pós-venda'})
 await dimensions.getByRole('button',{name:'Motivo',exact:true}).click()
 await expect(page.locator('[data-table-id="posvenda.analysis.reason"]')).toBeVisible()
 await dimensions.getByRole('button',{name:'UF',exact:true}).click()
 await expect(page.locator('[data-table-id="posvenda.analysis.uf"]')).toBeVisible()
 await settled();await page.screenshot({path:'.local/runtime/assistencias-abertas.png',fullPage:true})
 await page.getByRole('button',{name:'Emitidas',exact:true}).click()
 await expect(page.locator('[data-metric-id="posvenda.documents"]')).toContainText('Assistências emitidas')
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 await dimensions.getByRole('button',{name:'Pesquisa de documentos',exact:true}).click()
 const nextPage=page.waitForResponse(response=>response.url().includes('/posvenda/assistencias?')&&new URL(response.url()).searchParams.get('section')==='details')
 await page.getByRole('button',{name:'Próxima página',exact:true}).click()
 const detailPayload=await (await nextPage).json()
 expect(detailPayload.table.rows).toHaveLength(20)
 expect(detailPayload.series).toBeUndefined()
 expect(detailPayload.metrics).toBeUndefined()
 await expect(page.locator('.table-footer')).toContainText('21–40')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 const dialog=page.getByRole('dialog');await expect(dialog).toBeVisible()
 await dialog.getByRole('tab',{name:'Localização',exact:true}).click()
 await dialog.getByLabel('Estado (UF)',{exact:true}).selectOption('MG')
 await dialog.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(dialog).not.toBeVisible();await expect(page.locator('.aftersales-active')).toContainText('MG')
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
 await page.getByRole('link',{name:'Cancelamentos',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Cancelamentos de venda',exact:true})).toBeVisible()
 await expect(page.locator('[data-metric-id="posvenda.orders"]')).toContainText('Pedidos afetados')
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 await settled();await page.screenshot({path:'.local/runtime/cancelamentos-venda.png',fullPage:true})
 await page.getByRole('link',{name:'Devoluções',exact:true}).click()
 await expect(page.getByRole('heading',{name:'Devoluções',exact:true})).toBeVisible()
 await expect(page.locator('[data-metric-id="posvenda.quantity"]')).toContainText('Quantidade devolvida')
 await expect(page.locator('.aftersales-metrics')).toHaveAttribute('aria-busy','false')
 const data=await (await page.request.get('http://127.0.0.1:3002/api/v1/posvenda/devolucoes')).json()
 expect(data.total).toBeGreaterThan(0);expect(data.table.rows.every((row:{pedido_id:number})=>row.pedido_id>0)).toBeTruthy()
 await settled();await page.screenshot({path:'.local/runtime/devolucoes.png',fullPage:true})
 const csv=await page.request.get('http://127.0.0.1:3002/api/v1/posvenda/devolucoes?export=csv')
 expect(csv.ok()).toBeTruthy();expect(await csv.text()).toContain('Pedido original')
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2)).toBe(false)
 await settled();await page.screenshot({path:'.local/runtime/posvenda-mobile.png',fullPage:true})
 expect(errors).toEqual([])
})
