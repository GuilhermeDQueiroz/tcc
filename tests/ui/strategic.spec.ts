import {test,expect} from '@playwright/test'

test('strategic dashboard loads real sources, filters history and preserves compact responsive charts',async({page})=>{
 test.setTimeout(120_000)
 const errors:string[]=[]
 page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/estrategico')
 await expect(page.getByRole('heading',{name:'Visão Estratégica',exact:true})).toBeVisible()
 await expect(page.locator('.strategic-dashboard')).toBeVisible()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 await expect(page.locator('[data-metric-id^="strategic."]')).toHaveCount(7)
 const response=await page.request.get('/api/v1/logistica/estrategico')
 expect(response.ok()).toBeTruthy()
 const data=await response.json()
 expect(data.meta.history.records).toBeGreaterThan(0)
 expect(data.meta.publications.billing.version).toBeTruthy()
 expect(data.meta.publications.logistics.version).toBeTruthy()
 await expect(page.locator('[data-series-id^="strategic."] canvas')).toHaveCount(5,{timeout:30_000})
 for(const series of data.series)await expect(page.locator(`[data-series-id="${series.id}"]`).getByRole('heading')).toBeVisible()
 await page.screenshot({path:'.local/strategic-overview.png',fullPage:true})
 await page.getByRole('button',{name:'Semanas',exact:true}).click()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await expect(page.locator('[data-series-id="strategic.tonnage"]')).toContainText('Toneladas faturadas · semana')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Filtros · Visão Estratégica'})).toBeVisible()
 await page.getByLabel('Faturamento inicial', {exact:true}).fill(data.meta.history.end.slice(0,7)+'-01')
 await page.getByLabel('Faturamento final', {exact:true}).fill(data.meta.history.end)
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await expect(page.locator('.strategic-active-filters')).toContainText('Faturamento')
 await expect(page.locator('[data-metric-id="strategic.loads"] strong')).toHaveText(new Intl.NumberFormat('pt-BR',{maximumFractionDigits:0}).format(data.metrics.find((metric:{id:string})=>metric.id==='strategic.loads').value))
 await page.screenshot({path:'.local/strategic-desktop.png',fullPage:true})
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 const uf=page.getByRole('combobox',{name:'Estado (UF)',exact:true})
 await uf.fill('SP');await uf.press('ArrowDown');await uf.press('Enter');await uf.press('Tab')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Filtros · Visão Estratégica'})).toHaveCount(0)
 await expect(page.locator('.strategic-active-filters')).toContainText('UF: SP')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await page.getByRole('button',{name:'Remover filtro UF: SP',exact:true}).click()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 const delivery=page.getByRole('combobox',{name:'Entrega / retirada',exact:true})
 await delivery.fill('ENTREGA');await delivery.press('ArrowDown');await delivery.press('Enter');await delivery.press('Tab')
 const deliveredResponse=page.waitForResponse(response=>response.url().includes('/logistica/estrategico?')&&response.request().method()==='GET')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 const delivered=await (await deliveredResponse).json()
 expect(delivered.metrics.find((metric:{id:string})=>metric.id==='strategic.loads').value).toBeGreaterThan(0)
 expect(delivered.meta.history.records).toBeGreaterThan(0)
 expect(delivered.options.TIPO_ENTREGA).toEqual(['ENTREGA','RETIRA'])
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await page.getByRole('button',{name:'Limpar todos',exact:true}).click()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await page.setViewportSize({width:390,height:844})
 await expect(page.locator('[data-metric-id^="strategic."]')).toHaveCount(7)
 const overflow=await page.evaluate(()=>document.documentElement.scrollWidth>window.innerWidth+2)
 expect(overflow).toBe(false)
 await page.waitForFunction(()=>document.querySelector('.sidebar')!.getBoundingClientRect().right<=0)
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{})))})
 await page.screenshot({path:'.local/strategic-mobile.png',fullPage:true})
 expect(errors).toEqual([])
})
