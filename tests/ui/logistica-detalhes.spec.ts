import {test,expect} from '@playwright/test'

test('carga e pedido selecionados atualizam cards e detalham grupo, pedido e item',async({page})=>{
 test.setTimeout(120000)
 await page.goto('/cargas')
 const loads=page.locator('[data-table-id="logistica-cargas"]')
 const orders=page.locator('[data-table-id="logistica-pedidos"]')
 const cards=page.locator('.logistics-metrics [data-testid="metric-card"]')
 await expect(loads.locator('tbody tr').first()).toBeVisible({timeout:60000})
 await expect(cards).toHaveCount(12)
 const loadRow=loads.locator('tbody tr:not(.child-row)').first()
 const loadId=(await loadRow.getAttribute('data-row-id'))!.replace('carga-','')
 await loadRow.getByRole('button',{name:'Selecionar Carga '+loadId}).click()
 await expect(page.locator('.logistics-selection')).toContainText('Carga '+loadId+' selecionada')
 await expect(cards).toHaveCount(5)
 await expect(page.locator('[data-metric-id="logistica.loads"] strong')).toHaveText('1')
 await expect(loadRow.locator('.expand-row')).toBeVisible()
 await loadRow.locator('.expand-row').click()
 const group=loads.locator('tbody tr[data-row-id*="-grupo-"]').first()
 await expect(group).toContainText('Grupo')
 await group.locator('.expand-row').click()
 await expect(loads.locator('tbody tr[data-row-id*="-pedido-"]').first()).toBeVisible()
 const orderRow=orders.locator('tbody tr:not(.child-row)').first()
 const orderId=(await orderRow.getAttribute('data-row-id'))!.replace('pedido-','')
 await orderRow.getByRole('button',{name:'Selecionar Pedido '+orderId}).click()
 await expect(page.locator('.logistics-selection')).toContainText('Pedido '+orderId+' selecionado')
 await expect(cards).toHaveCount(12)
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1')
 const item=orders.locator('tbody tr.child-row').first()
 await expect(item).toContainText(/\d+ - .+ · \d+ - /)
 await orders.locator('tbody tr[data-row-id="pedido-'+orderId+'"]').getByRole('button',{name:'Selecionar Pedido '+orderId}).click()
 await expect(page.locator('.logistics-selection')).toContainText('Nenhuma seleção')
 await expect(cards).toHaveCount(12)
})
