test('the project proxy reaches its API and an older open payload cannot blank the page',async({page,request})=>{
 test.setTimeout(120000)
 const health=await request.get('/api/v1/health')
 expect(health.ok()).toBe(true)
 expect((await health.json()).status).toBe('ok')
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.route('**/api/v1/bi/abertos/resumo?**',async route=>{
  const response=await route.fetch()
  const payload=await response.json()
  payload.metrics=payload.metrics.filter((metric:{id:string})=>metric.id!=='abertos.resumo.revenuePerTon')
  await route.fulfill({response,json:payload})
 })
 await page.goto('/abertos')
 await expect(page.locator('[data-metric-id="abertos.resumo.value"]')).toBeVisible({timeout:90000})
 await expect(page.locator('[data-series-id="abertos.resumo.Mes_Grupo"]')).toBeVisible()
 await expect(page.locator('[data-metric-id="abertos.resumo.revenuePerTon"]')).toHaveCount(0)
 expect(errors).toEqual([])
})

