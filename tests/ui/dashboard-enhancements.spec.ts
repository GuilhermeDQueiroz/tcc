test('clicking the selected dimension again clears only that cross filter',async({page})=>{
 test.setTimeout(120000)
 await page.goto('/abertos')
 const value=page.locator('[data-metric-id="abertos.resumo.value"] > strong')
 await expect(value).toBeVisible({timeout:60000})
 const initial=await value.textContent()
 const section=page.locator('#open-dimensions')
 await section.getByRole('button',{name:'UF',exact:true}).click()
 const table=section.locator('[data-table-id="abertos.dimensoes.UF"]')
 await expect(table.locator('tbody .cell-link').first()).toBeVisible({timeout:60000})
 const state=(await table.locator('tbody .cell-link').first().textContent())!.trim()
 await table.locator('tbody .cell-link').first().click()
 await expect(page.locator('.filter-chips')).toContainText(state)
 await expect(value).not.toHaveText(initial||'',{timeout:60000})
 await table.locator('tbody .cell-link').filter({hasText:state}).first().click()
 await expect(page.locator('.filter-chips')).toHaveCount(0)
 await expect(value).toHaveText(initial||'',{timeout:60000})
})

