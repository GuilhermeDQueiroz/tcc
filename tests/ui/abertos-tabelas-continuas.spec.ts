import {test,expect} from '@playwright/test'
test.use({baseURL:'http://127.0.0.1:3002'})
test.setTimeout(90_000)

test('abertos mantém tabelas completas, totais e participação alinhados e rolagem contida',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/abertos')
 await expect(page.locator('.loading-screen')).toHaveCount(0)
 const dimensions=page.locator('.overview-dimensions')
 const table=dimensions.locator('.analytic-table')
 await expect(table.locator('tbody tr').first()).toBeVisible()
 await expect(table.locator('.loading-state')).toHaveCount(0)
 await expect(table.locator('.table-footer')).toHaveCount(0)
 await expect(dimensions.locator(':scope > .panel-heading h2')).toHaveText('Análise por dimensão')
 await dimensions.scrollIntoViewIfNeeded()
 await page.waitForFunction(()=>!document.getAnimations().some(a=>a.playState==='running'))
 const fill=await table.locator('.table-scroll').evaluate(el=>({table:el.querySelector('table')!.getBoundingClientRect().height,viewport:el.clientHeight,footerBottom:el.querySelector('tfoot')!.getBoundingClientRect().bottom,viewportBottom:el.getBoundingClientRect().top+el.clientHeight}))
 expect(fill.table).toBeGreaterThanOrEqual(fill.viewport-1)
 expect(Math.abs(fill.footerBottom-fill.viewportBottom)).toBeLessThanOrEqual(2)
 const offsets=await table.evaluate(root=>{
  const textRight=(element:Element)=>{const range=document.createRange();range.selectNodeContents(element);return range.getBoundingClientRect().right}
  const first=root.querySelector('tbody tr')!,footer=root.querySelector('tfoot tr')!
  return [...first.querySelectorAll('td')].map((cell,index)=>{
   const total=footer.children[index]!,body=cell.getBoundingClientRect(),foot=total.getBoundingClientRect()
   return {left:Math.abs(body.left-foot.left),right:Math.abs(body.right-foot.right),numeric:cell.classList.contains('numeric'),textDelta:Math.abs(textRight(cell.querySelector('.progress-value')||cell)-textRight(total)),padding:getComputedStyle(cell).paddingRight,totalPadding:getComputedStyle(total).paddingRight}
  })
 })
 for(const offset of offsets){expect(offset.left).toBeLessThan(1);expect(offset.right).toBeLessThan(1);if(offset.numeric){expect(offset.textDelta).toBeLessThan(1);expect(offset.padding).toEqual(offset.totalPadding)}}
 const percents=await table.locator('.progress-value').evaluateAll(elements=>elements.map(el=>getComputedStyle(el).width))
 expect(new Set(percents).size).toBe(1)
 await dimensions.screenshot({path:'.local/abertos-totalizadores.png'})
 const waiting=page.waitForResponse(r=>r.url().includes('/bi/abertos/dimensoes?')&&new URL(r.url()).searchParams.get('dimension')==='CIDADE')
 await dimensions.getByRole('button',{name:'Cidade',exact:true}).click()
 const cities=await (await waiting).json()
 await expect(table.locator('tbody tr:not(.child-row)')).toHaveCount(cities.tables[0].tree.length)
 await expect(table.locator('.table-footer')).toHaveCount(0)
 const before=(await table.boundingBox())!.height
 await table.locator('.table-scroll').evaluate(el=>el.scrollTop=el.scrollHeight)
 await expect(table.locator('tbody tr').last()).toBeVisible()
 const details=page.waitForResponse(r=>r.url().includes('/bi/abertos/detalhes?')&&new URL(r.url()).searchParams.get('grain')==='order')
 await dimensions.getByRole('button',{name:'Pesquisa de Pedidos',exact:true}).click()
 const orders=await (await details).json()
 await expect(table.locator('tbody tr')).toHaveCount(orders.total)
 await expect(table.locator('.table-footer')).toHaveCount(0)
 await expect(table.locator('.loading-state')).toHaveCount(0)
 await expect(table.locator('.panel-heading h2')).toHaveText('Pesquisa de pedidos')
 expect(Math.abs((await table.boundingBox())!.height-before)).toBeLessThan(1)
 await table.locator('.table-scroll').evaluate(el=>el.scrollTop=el.scrollHeight)
 await expect(table.locator('tbody tr').last()).toBeVisible()
 const bounds=await table.locator('.table-scroll').evaluate(el=>{const viewport=el.parentElement!.getBoundingClientRect(),scroll=el.getBoundingClientRect();return {right:scroll.right-viewport.right,bottom:scroll.bottom-viewport.bottom,color:getComputedStyle(el).scrollbarColor,width:getComputedStyle(el).scrollbarWidth}})
 expect(bounds.right).toBeLessThanOrEqual(1);expect(bounds.bottom).toBeLessThanOrEqual(1);expect(bounds.width).toBe('thin');expect(bounds.color).not.toBe('auto')
 await page.waitForFunction(()=>!document.getAnimations().some(a=>a.playState==='running'))
 await table.screenshot({path:'.local/abertos-pedidos-sem-paginacao.png'})
 await dimensions.getByLabel('Pesquisar pedidos',{exact:true}).fill('__TCC_sem_registros_scroll__')
 await dimensions.getByRole('button',{name:'Pesquisar',exact:true}).click()
 await expect(table.locator('.empty-table')).toBeVisible()
 expect(Math.abs((await table.boundingBox())!.height-before)).toBeLessThan(1)
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 expect(errors).toEqual([])
})
