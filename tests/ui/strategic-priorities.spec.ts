import {test,expect} from '@playwright/test'

test('strategic priorities navigate to the actual open-order cut and retain common filters',async({page})=>{
 test.setTimeout(120_000)
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const balance=await page.request.get('/api/v1/logistica/formacao')
 expect(balance.ok()).toBe(true)
 const balanceData=await balance.json()
 const state=balanceData.tables[0].rows.find((order:{uf:string;quantidade_sem_carga:number})=>/^[A-Z]{2}$/.test(order.uf)&&order.quantidade_sem_carga>=0.000001)?.uf
 expect(state).toBeTruthy()
 await page.goto('/estrategico')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 const priorities=page.getByRole('region',{name:'Prioridades da carteira'})
 await expect(priorities.locator('[data-metric-id^="priority."]')).toHaveCount(4)
 await expect(page.getByLabel('Definição dos indicadores')).toContainText('OTIF · faturamento no prazo.')
 await expect(page.getByLabel('Definição dos indicadores')).toContainText('Não comprova entrega ao cliente nem atendimento integral')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 const uf=page.getByRole('combobox',{name:'Estado (UF)',exact:true})
 await uf.fill(state);await uf.press('ArrowDown');await uf.press('Enter');await uf.press('Tab')
 await page.getByLabel('Faturamento inicial',{exact:true}).fill('2026-08-01')
 await page.getByLabel('Faturamento final',{exact:true}).fill('2026-08-31')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 const responsePromise=page.waitForResponse(response=>response.url().includes('/logistica/formacao?'))
 await page.getByRole('button',{name:'Analisar Pedidos com saldo sem carga',exact:true}).click()
 const response=await responsePromise;expect(response.ok()).toBe(true)
 const url=new URL(response.url())
 expect(url.searchParams.getAll('uf')).toEqual([state])
 expect(url.searchParams.get('freeQuantityMin')).toBe('0.000001')
 expect(url.searchParams.has('status')).toBe(false)
 expect(url.searchParams.has('forecastStart')).toBe(false)
 expect(url.searchParams.has('forecastEnd')).toBe(false)
 const data=await response.json()
 expect(data.tables[0].rows.length).toBeGreaterThan(0)
 expect(data.tables[0].rows.every((order:{uf:string;quantidade_sem_carga:number})=>order.uf===state&&order.quantidade_sem_carga>0)).toBe(true)
 await expect(page).toHaveURL(/\/cargas$/)
 await expect(page.locator('h1')).toHaveText('Formação de Cargas')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 await page.getByRole('link',{name:'Visão Estratégica',exact:true}).click()
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 const overdueResponse=page.waitForResponse(response=>response.url().includes('/logistica/formacao?'))
 await page.getByRole('button',{name:'Analisar Previsão vencida',exact:true}).click()
 expect(new URL((await overdueResponse).url()).searchParams.get('forecastStatus')).toBe('overdue')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:30_000})
 expect(errors).toEqual([])
})

test('priority cards and definitions remain usable on a narrow screen',async({page})=>{
 test.setTimeout(90_000)
 await page.setViewportSize({width:390,height:844});await page.goto('/estrategico')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 await page.getByRole('heading',{name:'Prioridades da carteira',exact:true}).scrollIntoViewIfNeeded()
 await expect(page.getByRole('button',{name:'Consultar pedidos e cargas',exact:true})).toBeVisible()
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{})))})
 await page.screenshot({path:'.local/strategic-priorities-mobile.png',fullPage:true})
})
