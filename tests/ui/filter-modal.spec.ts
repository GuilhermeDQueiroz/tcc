import {test,expect,type Page} from '@playwright/test'
test.setTimeout(120_000)
async function openFilters(page:Page,area='abertos'){
 await page.goto(`/${area}`)
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 await page.getByRole('button',{name:'Filtros Avançados',exact:true}).click()
 const dialog=page.getByRole('dialog',{name:'Filtros da análise',exact:true})
 await expect(dialog).toBeVisible()
 await expect(dialog.locator('.loading-state')).toHaveCount(0)
 return dialog
}

test('filtros compartilham estilo do projeto; seleção real por teclado e layout móvel',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const dialog=await openFilters(page)
 await expect(dialog.locator('.filter-modal-title')).toHaveCSS('font-size','16px')
 await expect(dialog.locator('.filter-modal-title')).toHaveCSS('color','rgb(0, 106, 58)')
 await expect(dialog.locator('.filter-control-input').first()).toHaveCSS('border-radius','10px')
 await expect(dialog.getByLabel('Faturamento de',{exact:true})).toHaveCount(0)
 await dialog.getByRole('tab',{name:'Localização',exact:true}).click()
 await expect(dialog.getByRole('tab',{name:'Localização',exact:true})).toHaveCSS('background-color','rgb(226, 242, 217)')
 const uf=dialog.getByRole('combobox',{name:'Estado (UF)',exact:true})
 await uf.click()
 const list=dialog.getByRole('listbox',{name:'Opções de Estado (UF)',exact:true})
 const first=list.getByRole('option').first(),value=(await first.textContent())!.trim()
 await uf.press('ArrowDown');await uf.press('Enter')
 await expect(first).toHaveAttribute('aria-selected','true')
 await expect(dialog.getByRole('button',{name:`Remover ${value}`,exact:true})).toBeVisible()
 await uf.press('Escape');await expect(uf).toHaveAttribute('aria-expanded','false')
 await expect(dialog).toBeVisible()
 await dialog.getByRole('button',{name:`Remover ${value}`,exact:true}).click()
 await expect(dialog.getByRole('tab',{name:'Localização',exact:true})).not.toContainText('(1)')
 await page.screenshot({path:'tests/ui/screenshots/filter-aligned-desktop.png',animations:'disabled'})
 for(const width of [390,320]){
  await page.setViewportSize({width,height:844})
  await expect(dialog.getByRole('button',{name:'Aplicar filtros',exact:true})).toBeInViewport()
  await expect(dialog.getByRole('button',{name:'Cancelar',exact:true})).toBeInViewport()
  await expect(dialog.getByRole('button',{name:'Limpar filtros',exact:true})).toBeInViewport()
  expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
  const last=dialog.getByRole('combobox',{name:'Microregião',exact:true})
  await last.scrollIntoViewIfNeeded();await last.click()
  const bounds=await dialog.getByRole('listbox',{name:'Opções de Microregião',exact:true}).boundingBox()
  const body=await dialog.locator('.filter-modal-body').boundingBox()
  expect(bounds!.y).toBeGreaterThanOrEqual(body!.y-1)
  expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(body!.y+body!.height+1)
  await last.press('Escape')
  await page.screenshot({path:`tests/ui/screenshots/filter-aligned-${width}.png`,animations:'disabled'})
 }
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click()
 await expect(dialog).toHaveCount(0)
 await expect(page.getByRole('button',{name:'Filtros',exact:true})).toBeFocused()
 await page.setViewportSize({width:1440,height:900})
 await page.getByRole('button',{name:'Filtros Avançados',exact:true}).click()
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click()
 await expect(page.getByRole('button',{name:'Filtros Avançados',exact:true})).toBeFocused()
 expect(errors).toEqual([])
})

test('atalhos respeitam o legacy, edição é local e validação bloqueia envio inválido',async({page})=>{
 const dialog=await openFilters(page,'faturados')
 const payload=await (await page.request.get('/api/v1/bi/faturados/filtros')).json()
 const range=payload.dates.emission as [string,string]
 await dialog.getByLabel('Emissão de',{exact:true}).fill(range[0])
 await dialog.getByLabel('Emissão até',{exact:true}).fill(range[1])
 const current=new Intl.DateTimeFormat('en-CA',{timeZone:'America/Sao_Paulo',year:'numeric',month:'2-digit',day:'2-digit'}).format(new Date())
 await dialog.getByRole('button',{name:'Este Mês',exact:true}).click()
 await expect(dialog.getByLabel('Faturamento de',{exact:true})).toHaveValue(`${current.slice(0,7)}-01`)
 await expect(dialog.getByLabel('Faturamento até',{exact:true})).toHaveValue(current)
 await expect(dialog.getByLabel('Emissão de',{exact:true})).toHaveValue(range[0])
 await expect(dialog.getByLabel('Emissão até',{exact:true})).toHaveValue(range[1])
 await dialog.getByRole('button',{name:`Ano ${current.slice(0,4)}`,exact:true}).click()
 await expect(dialog.getByLabel('Faturamento de',{exact:true})).toHaveValue(`${current.slice(0,4)}-01-01`)
 await expect(dialog.getByLabel('Faturamento até',{exact:true})).toHaveValue(`${current.slice(0,4)}-12-31`)
 await dialog.getByLabel('Aplicar atalhos em',{exact:true}).selectOption('emission')
 await dialog.getByRole('button',{name:'Hoje',exact:true}).click()
 await expect(dialog.getByLabel('Emissão de',{exact:true})).toHaveValue(current)
 await expect(dialog.getByLabel('Emissão até',{exact:true})).toHaveValue(current)
 await expect(dialog.getByLabel('Faturamento de',{exact:true})).toHaveValue(`${current.slice(0,4)}-01-01`)
 let sent=0;page.on('request',request=>{if(request.url().includes('/bi/faturados/semanal?'))sent++})
 await dialog.getByLabel('Emissão até',{exact:true}).fill('')
 await dialog.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(dialog.getByRole('alert')).toContainText('duas datas')
 expect(sent).toBe(0)
 await dialog.getByRole('button',{name:'Limpar Período',exact:true}).click()
 await dialog.getByRole('tab',{name:'Valores e quantidade',exact:true}).click()
 await dialog.getByLabel('Operador do valor',{exact:true}).selectOption('>')
 await dialog.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(dialog.getByRole('alert')).toContainText('número válido')
 expect(sent).toBe(0)
 await dialog.getByLabel('Valor do pedido',{exact:true}).fill('0')
 const waiting=page.waitForResponse(response=>response.url().includes('/bi/faturados/semanal?') && response.status()===200)
 await dialog.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 const response=await waiting
 const filters=JSON.parse(new URL(response.url()).searchParams.get('filters')!)
 expect(filters).toEqual({value:{operator:'>',value:0}})
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 await page.getByRole('button',{name:'Filtros Avançados',exact:true}).click()
 await expect(dialog.getByLabel('Valor do pedido',{exact:true})).toHaveValue('0')
 await dialog.getByRole('tab',{name:'Período',exact:true}).click()
 await dialog.getByRole('button',{name:'Hoje',exact:true}).click()
 await dialog.getByRole('button',{name:'Cancelar',exact:true}).click()
 await page.getByRole('button',{name:'Filtros Avançados',exact:true}).click()
 await expect(dialog.getByLabel('Faturamento de',{exact:true})).toHaveValue('')
})
