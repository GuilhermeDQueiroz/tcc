import {test,expect} from '@playwright/test'

test('indicator guide opens collapsed, keeps fixed size, ignores backdrop clicks and resets on reopening',async({page})=>{
 test.setTimeout(180000)
 await page.goto('/estrategico')
 await expect(page.locator('.strategic-metrics>.metric-card')).toHaveCount(13,{timeout:60000})
 await expect(page.locator('.loading-state')).toHaveCount(0,{timeout:60000})
 for(const viewport of [{width:1440,height:900},{width:390,height:844}]){
  await page.setViewportSize(viewport)
  await page.getByRole('button',{name:'Sobre os indicadores',exact:true}).click()
  const dialog=page.getByRole('dialog',{name:'Sobre os indicadores',exact:true})
  await expect(dialog).toBeVisible();await expect(dialog.locator('details[open]')).toHaveCount(0)
  const before=await dialog.boundingBox()
  expect(before!.height).toBe(Math.min(720,viewport.height-24))
  await page.mouse.click(2,2);await expect(dialog).toBeVisible()
  await dialog.locator('.info-section').first().locator('summary').click()
  await expect(dialog.locator('details[open]')).toHaveCount(1)
  const after=await dialog.boundingBox();expect(after!.height).toBe(before!.height);expect(after!.width).toBe(before!.width)
  expect(await dialog.locator('.indicators-info-body').evaluate(element=>element.scrollHeight>element.clientHeight)).toBe(true)
  await dialog.getByRole('button',{name:'Fechar informações',exact:true}).click()
  await page.getByRole('button',{name:'Sobre os indicadores',exact:true}).click()
  await expect(dialog.locator('details[open]')).toHaveCount(0)
  await page.keyboard.press('Escape');await expect(dialog).not.toBeVisible()
  await expect(page.getByRole('button',{name:'Sobre os indicadores',exact:true})).toBeFocused()
 }
})

test('filters, settings, expanded analyses and goals ignore outside clicks but retain explicit closing',async({page})=>{
 test.setTimeout(180000)
 await page.goto('/estrategico')
 await expect(page.locator('.strategic-metrics>.metric-card')).toHaveCount(13,{timeout:60000})
 await expect(page.locator('.loading-state')).toHaveCount(0,{timeout:60000})
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 const filter=page.getByRole('dialog',{name:'Filtros · Visão estratégica',exact:true})
 await expect(filter).toBeVisible();await page.mouse.click(2,2);await expect(filter).toBeVisible()
 await filter.getByRole('button',{name:'Fechar filtros',exact:true}).click();await expect(filter).toHaveCount(0)
 const chart=page.locator('[data-series-id="strategic.tonnage"]')
 await chart.getByRole('button',{name:'Configurar PESO POR MÊS',exact:true}).click()
 const config=page.getByRole('region',{name:'Configurações de PESO POR MÊS',exact:true})
 await expect(config).toBeVisible();await page.mouse.click(2,2);await expect(config).toBeVisible()
 await config.getByRole('button',{name:'Expandir em tela cheia',exact:true}).click()
 const expanded=page.getByRole('dialog',{name:'PESO POR MÊS',exact:true})
 await expect(expanded).toBeVisible();await page.mouse.click(2,2);await expect(expanded).toBeVisible()
 await expanded.getByRole('button',{name:'Sair da tela cheia',exact:true}).click();await expect(expanded).toHaveCount(0)
 await page.goto('/emitidos')
 await expect(page.locator('.loading-state')).toHaveCount(0,{timeout:60000})
 await page.getByRole('button',{name:'Metas',exact:true}).click()
 const goals=page.getByRole('dialog',{name:'Configurar metas',exact:true})
 await expect(goals).toBeVisible();await page.mouse.click(2,2);await expect(goals).toBeVisible()
 await goals.getByRole('button',{name:'Fechar metas',exact:true}).click();await expect(goals).toHaveCount(0)
})
