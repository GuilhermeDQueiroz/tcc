import {test,expect} from '@playwright/test'

test('logistics overview shows only logistics backlog with legacy colors and keeps loads in formation',async({page})=>{
 test.setTimeout(120_000)
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const response=await page.request.get('/api/v1/logistica/estrategico');expect(response.ok()).toBe(true)
 const data=await response.json(),backlog=data.meta.backlog
 await page.goto('/estrategico')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 await expect(page.locator('.strategic-metrics .metric-card')).toHaveCount(13)
 for(const id of ['loads','valueLoad','weightKg','orders30'])await expect(page.locator(`[data-metric-id="strategic.${id}"]`)).toHaveCount(0)
 const card=page.locator('[data-metric-id="strategic.backlogReal"]')
 await expect(card).toContainText('Backlog logístico')
 await expect(card.locator('.backlog-units')).toHaveCount(0)
 await expect(card).toContainText(backlog.state.label)
 await expect(card).toHaveAttribute('data-tone',backlog.state.tone)
 const days=(value:number)=>new Intl.NumberFormat('pt-BR',{minimumFractionDigits:1,maximumFractionDigits:1}).format(value)
 await expect(card.locator(':scope > strong')).toHaveText(days(backlog.realDays)+' dias')
 expect(backlog.generalDays).toBeUndefined()
 const colors:Record<string,string>={good:'rgb(0, 106, 58)',warning:'rgb(198, 146, 20)',critical:'rgb(220, 38, 38)',neutral:'rgb(100, 116, 139)'}
 await expect(card).toHaveCSS('border-left-color',colors[backlog.state.tone]!)
 await expect(card.locator('.backlog-state')).toHaveCSS('color',colors[backlog.state.tone]!)
 await card.getByRole('button',{name:'Sobre Backlog logístico',exact:true}).focus()
 await expect(card.getByRole('tooltip')).toBeVisible()
 await expect(card.getByRole('tooltip')).toHaveText('Quantos dias de faturamento médio equivalem ao saldo logístico atual.')
 await page.getByRole('button',{name:'Sobre os indicadores'}).click()
 await page.getByText('Indicadores e cálculos',{exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Sobre os indicadores'})).toContainText('Faturado Parcial')
 await page.getByRole('button',{name:'Fechar informações'}).click()
 await page.getByRole('heading',{name:'Visão estratégica',exact:true}).click()
 await page.screenshot({path:'.local/logistics-backlog-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 await page.waitForFunction(()=>document.querySelector('.sidebar')!.getBoundingClientRect().right<=0)
 await page.evaluate(async()=>{await Promise.all(document.getAnimations().filter(animation=>animation.effect?.getTiming().iterations!==Infinity).map(animation=>animation.finished.catch(()=>{})))})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 await expect(card.locator('.backlog-value')).toHaveCount(0)
 await expect(page.locator('[data-metric-id="strategic.portfolioValue"]')).toBeVisible()
 await page.screenshot({path:'.local/logistics-backlog-mobile.png',fullPage:true})
 await page.setViewportSize({width:1440,height:900})
 await page.goto('/cargas')
 await expect(page.locator('.loading-screen')).toHaveCount(0,{timeout:60_000})
 const loadCard=page.locator('[data-metric-id="logistica.loads"]')
 await expect(loadCard).toHaveCount(1);await expect(loadCard).toContainText('Cargas em aberto')
 const formation=await page.request.get('/api/v1/logistica/formacao').then(response=>response.json())
 await expect(loadCard.locator('strong')).toHaveText(new Intl.NumberFormat('pt-BR').format(formation.metrics.find((metric:{id:string})=>metric.id==='logistica.loads').value))
 await page.screenshot({path:'.local/logistics-loads-desktop.png',fullPage:true})
 await page.setViewportSize({width:390,height:844})
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth+2)).toBe(true)
 expect(errors).toEqual([])
})
