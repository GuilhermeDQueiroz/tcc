test('modal e listas cabem em desktop e em telas de 390 e 320 pixels',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const dialog=await open(page)
 for(const width of [1440,390,320]){
  await page.setViewportSize({width,height:844})
  await dialog.getByRole('tab',{name:'Localização',exact:true}).click()
  const city=dialog.getByRole('combobox',{name:'Cidade',exact:true})
  await city.scrollIntoViewIfNeeded();await city.click()
  const bounds=await dialog.getByRole('listbox',{name:'Opções de Cidade'}).boundingBox(),body=await dialog.locator('.filter-modal-body').boundingBox()
  expect(bounds!.y).toBeGreaterThanOrEqual(body!.y-1);expect(bounds!.y+bounds!.height).toBeLessThanOrEqual(body!.y+body!.height+1)
  await city.press('Escape')
  const box=await dialog.boundingBox();expect(box!.x).toBeGreaterThanOrEqual(0);expect(box!.x+box!.width).toBeLessThanOrEqual(width)
  expect(await dialog.evaluate(el=>el.scrollWidth<=el.clientWidth)).toBe(true)
  await page.screenshot({path:`.local/logistica-filtros-${width}.png`,animations:'disabled'})
 }
 await dialog.getByRole('tab',{name:'Valores',exact:true}).click()
 await dialog.getByRole('button',{name:'Aplicar filtros',exact:true}).focus()
 await page.keyboard.press('Tab');await expect(dialog.getByRole('button',{name:'Fechar filtros',exact:true})).toBeFocused()
 await page.keyboard.press('Escape');await expect(dialog).toHaveCount(0)
 expect(errors).toEqual([])
})

