import {test,expect} from '@playwright/test'
test.use({baseURL:'http://127.0.0.1:3002'})
async function expectFilledTable(frame:import('@playwright/test').Locator){
 const geometry=await frame.evaluate(element=>{
  const scroll=element.querySelector('.table-scroll') as HTMLElement
  const table=scroll.querySelector('table')!
  const total=table.querySelector('tfoot')!
  return {tableHeight:table.getBoundingClientRect().height,viewportHeight:scroll.clientHeight,
   bottomGap:scroll.getBoundingClientRect().top+scroll.clientHeight-total.getBoundingClientRect().bottom}
 })
 expect(geometry.tableHeight).toBeGreaterThanOrEqual(geometry.viewportHeight-1)
 expect(Math.abs(geometry.bottomGap)).toBeLessThanOrEqual(2)
}

test('tabelas cruzadas reais: carga → pedidos e itens → cargas, limpeza e mapa',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const data=await (await request.get('/api/v1/logistica/formacao')).json()
 await page.goto('/cargas')
 const loads=page.locator('[data-table-id="logistica-cargas"]'),orders=page.locator('[data-table-id="logistica-pedidos"]')
 await expect(loads.locator('tbody tr').first()).toBeVisible();await expect(orders.locator('tbody tr').first()).toBeVisible()
 const baseline=await loads.boundingBox()
 const loadId=(await loads.locator('tbody tr').first().getAttribute('data-row-id'))!.replace('carga-','')
 const load=data.tables[1].rows.find((row:any)=>row.carga_id===loadId)
 await loads.locator('tbody tr').first().getByRole('button',{name:'Selecionar Carga '+loadId,exact:true}).click()
 await expect(page.locator('.logistics-selection')).toContainText('Carga '+loadId+' selecionada')
 await expect(loads.locator('.selected-row')).toHaveAttribute('data-row-id','carga-'+loadId)
 const orderIds=load.children.map((row:any)=>'pedido-'+row.pedido_id).sort((a:string,b:string)=>a.localeCompare(b,'pt-BR',{numeric:true}))
 expect(await orders.locator('tbody tr:not(.child-row)').evaluateAll(rows=>rows.map(row=>row.getAttribute('data-row-id')))).toEqual(orderIds)
 const allocations=load.children.flatMap((row:any)=>row.children).map((row:any)=>row.id)
 const leaves=await orders.locator('tbody tr.child-row').evaluateAll(rows=>rows.map(row=>row.getAttribute('data-row-id')))
 expect(leaves.length).toBeGreaterThan(0);expect(leaves.every(id=>allocations.includes(id))).toBe(true)
 const qty=load.quantidade_alocada.toLocaleString('pt-BR',{maximumFractionDigits:4})
 await expect(orders.locator('tfoot td').nth(4)).toHaveText(qty)
 await expectFilledTable(orders)
 for(const label of await orders.locator('tbody .tree-identity .cell-link').all()){
  expect(await label.evaluate(element=>getComputedStyle(element).whiteSpace)).toBe('normal')
  expect(await label.evaluate(element=>element.scrollWidth<=element.clientWidth+1)).toBe(true)
 }
 const orderId=orderIds[0].replace('pedido-','')
 await orders.locator('[data-row-id="pedido-'+orderId+'"]').getByRole('button',{name:'Selecionar Pedido '+orderId,exact:true}).click()
 await expect(page.locator('.logistics-selection')).toContainText('Pedido '+orderId+' selecionado')
 const linked=data.tables[1].rows.filter((row:any)=>row.children.some((child:any)=>child.pedido_id===orderId))
 expect(await loads.locator('tbody tr:not(.child-row)').evaluateAll(rows=>rows.map(row=>row.getAttribute('data-row-id')))).toEqual(linked.map((row:any)=>row.id).sort((a:string,b:string)=>a.localeCompare(b,'pt-BR',{numeric:true})))
 const allocated=linked.flatMap((row:any)=>row.children).filter((row:any)=>row.pedido_id===orderId).reduce((sum:number,row:any)=>sum+row.quantidade_alocada,0)
 await expect(loads.locator('tfoot td').nth(3)).toHaveText(allocated.toLocaleString('pt-BR',{maximumFractionDigits:4}))
 await expect(page.locator('.logistics-coordinate-coverage')).toContainText('/ 1 no mapa')
 await expectFilledTable(loads)
 await expectFilledTable(page.locator('[data-table-id="logistica-destinos"]'))
 await page.locator('.logistics-workspace').screenshot({path:'.local/logistica-selecao-preenchida.png',animations:'disabled'})
 expect(Math.abs((await loads.boundingBox())!.height-baseline!.height)).toBeLessThan(2)
 await page.getByRole('button',{name:'Limpar seleção',exact:true}).click()
 await expect(page.locator('.logistics-selection')).toContainText('Nenhuma seleção')
 await expect(loads.locator('tbody tr:not(.child-row)')).toHaveCount(data.tables[1].rows.length)
 await expect(orders.locator('tbody tr:not(.child-row)')).toHaveCount(data.tables[0].rows.length)
 const map=page.locator('[data-series-id="logistica.destinos"]');await map.scrollIntoViewIfNeeded();await expect(map.locator('canvas')).toBeVisible()
 await page.getByRole('button',{name:'Aproximar mapa',exact:true}).click();await page.getByRole('button',{name:'Restaurar mapa',exact:true}).click()
 await expect(page.locator('.logistics-coordinate-coverage')).toContainText('/ 1.335 no mapa')
 await page.waitForFunction(()=>!document.getAnimations().some(animation=>animation.playState==='running'))
 await page.locator('.logistics-workspace').screenshot({path:'.local/logistica-workspace.png'})
 await page.locator('[data-table-id="logistica-destinos"] tbody tr').first().getByRole('button',{name:/Expandir/}).click()
 const cities=page.locator('[data-table-id="logistica-destinos"]'),cityRow=cities.locator('tbody tr.child-row').first()
 const destination=(await cityRow.getAttribute('data-row-id'))!.split('|'),uf=destination[0],city=destination.slice(1).join('|')
 await cityRow.getByRole('button',{name:'Selecionar '+city,exact:true}).click()
 const filtered=await (await request.get('/api/v1/logistica/formacao?'+new URLSearchParams({uf,city}))).json()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText(filtered.metrics[0].value.toLocaleString('pt-BR'))
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await page.getByRole('tab',{name:'Localização',exact:true}).click()
 await expect(page.getByRole('button',{name:'Remover '+uf,exact:true})).toBeVisible()
 await expect(page.getByRole('button',{name:'Remover '+city,exact:true})).toBeVisible()
 await expect(page.locator('.logistics-selection')).toContainText('Nenhuma seleção')
 await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1.335')
 expect(errors).toEqual([])
})
