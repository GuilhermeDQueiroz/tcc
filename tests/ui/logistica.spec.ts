import {test,expect} from '@playwright/test'
test.use({baseURL:'http://127.0.0.1:3002'})
test('formação de cargas: dados reais, hierarquias, filtros e loading preservam tabelas',async({page})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 await page.goto('/cargas')
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1.335')
 await expect(page.locator('[data-metric-id="logistica.none"] strong')).toHaveText('894')
 await expect(page.locator('[data-metric-id="logistica.partial"] strong')).toHaveText('10')
 await expect(page.locator('[data-metric-id="logistica.full"] strong')).toHaveText('431')
 await expect(page.locator('[data-metric-id="logistica.free"] strong')).toHaveText('27.818')
 await expect(page.locator('[data-metric-id="logistica.cubeLoad"] strong')).toHaveText('2.174,35 m³')
 await expect(page.locator('[data-metric-id="logistica.cubeFree"] strong')).toHaveText('4.553,72 m³')
 await expect(page.locator('h1')).toHaveText('Formação de Cargas')
 await expect(page.locator('.loading-screen')).toHaveCount(0)
 const orders=page.locator('[data-table-id="logistica-pedidos"]')
 await expect(orders.locator('table')).toBeVisible()
 const heightBefore=await orders.boundingBox()
 const firstCell=orders.locator('tbody tr').first().locator('td').first()
 await firstCell.locator('button').first().click()
 await expect(orders.locator('tbody tr')).not.toHaveCount(15)
 const loads=page.locator('[data-table-id="logistica-cargas"]')
 await expect(loads).toBeVisible()
 await loads.locator('tbody tr').first().locator('td').first().locator('button').first().click()
 await expect(loads.locator('tbody tr')).not.toHaveCount(15)
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await page.getByRole('tab',{name:'Cargas',exact:true}).click()
 await page.getByLabel('Situação de alocação',{exact:true}).selectOption('partial')
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('10')
 await expect(orders.locator('tbody tr')).toHaveCount(10)
 expect(Math.abs((await orders.boundingBox())!.height-heightBefore!.height)).toBeLessThan(2)
 let release:()=>void=()=>undefined,served:()=>void=()=>undefined
 const pending=new Promise<void>(resolve=>release=resolve),fulfilled=new Promise<void>(resolve=>served=resolve)
 await page.route('**/api/v1/logistica/formacao?**',async route=>{const response=await route.fetch();await pending;await route.fulfill({response});served()})
 await page.getByRole('button',{name:'Atualizar dados',exact:true}).click()
 await expect(orders.locator('.loading-state')).toBeVisible()
 await expect(orders.locator('table')).toBeAttached();await expect(orders.locator('tbody tr')).toHaveCount(10)
 release();await fulfilled;await page.unroute('**/api/v1/logistica/formacao?**')
 await expect(orders.locator('.loading-state')).toHaveCount(0)
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1.335')
 await page.getByRole('link',{name:'Pedidos em Aberto',exact:true}).click()
 await expect(page.locator('h1')).toHaveText('Análise de Pedidos em Aberto')
 await page.getByRole('link',{name:'Formação de Cargas',exact:true}).click()
 await expect(page.locator('h1')).toHaveText('Formação de Cargas')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await expect(page.getByRole('dialog',{name:'Filtros de formação de cargas'})).toBeVisible()
 await page.getByRole('button',{name:'Cancelar',exact:true}).click()
 await expect(page.locator('.logistics-page .loading-state')).toHaveCount(0)
 await page.waitForFunction(()=>!document.getAnimations().some(animation=>animation.playState==='running'))
 await page.screenshot({path:'.local/logistica-desktop.png',fullPage:true})
 await orders.scrollIntoViewIfNeeded()
 await page.waitForFunction(()=>!document.getAnimations().some(animation=>animation.playState==='running'))
 await page.screenshot({path:'.local/logistica-tabela.png'})
 expect(errors).toEqual([])
})

test('formação de cargas: navegação e filtros em tela pequena',async({page})=>{
 await page.setViewportSize({width:390,height:844});await page.goto('/cargas')
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1.335')
 await expect(page.locator('.loading-screen')).toHaveCount(0)
 expect(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth)).toBe(true)
 await page.getByRole('button',{name:'Abrir menu',exact:true}).click()
 await expect(page.getByRole('link',{name:'Formação de Cargas',exact:true})).toBeVisible()
 await page.getByRole('link',{name:'Formação de Cargas',exact:true}).click()
 await expect(page.locator('.sidebar')).not.toHaveClass(/mobile-open/)
 await page.waitForFunction(()=>!document.getAnimations().some(animation=>animation.playState==='running'))
 await page.screenshot({path:'.local/logistica-mobile.png',fullPage:true})
})
