import {test,expect} from '@playwright/test'
test.use({baseURL:'http://127.0.0.1:3002'})
test('cards visíveis, registros completos sem paginação, destinos hierárquicos e filtros em modal',async({page,request})=>{
 const data=await (await request.get('/api/v1/logistica/formacao')).json()
 await page.setViewportSize({width:1850,height:960});await page.goto('/cargas')
 await expect(page.locator('.metric-card')).toHaveCount(data.metrics.length)
 for(const metric of data.metrics)await expect(page.locator('[data-metric-id="'+metric.id+'"]')).toBeVisible()
 await expect(page.locator('.logistics-more-metrics,.logistics-filters')).toHaveCount(0)
 const loads=page.locator('[data-table-id="logistica-cargas"]'),orders=page.locator('[data-table-id="logistica-pedidos"]'),cities=page.locator('[data-table-id="logistica-destinos"]')
 for(const table of [loads,orders,cities])await expect(table.locator('.table-footer')).toHaveCount(0)
 for(const table of [loads,orders])await expect(table.locator('h2')).toBeHidden()
 await expect(loads.locator('tbody tr:not(.child-row)')).toHaveCount(data.tables[1].rows.length)
 await expect(orders.locator('tbody tr:not(.child-row)')).toHaveCount(data.tables[0].rows.length)
 await page.waitForFunction(()=>!document.getAnimations().some(a=>a.playState==='running'))
 await page.screenshot({path:'.local/logistica-todos-cards.png'})
 await loads.locator('.table-scroll').evaluate(el=>el.scrollTop=el.scrollHeight)
 await expect(loads.locator('tbody tr').last()).toBeVisible()
 await expect(page.locator('details.logistics-city-details')).toHaveCount(0)
 const expectedStates=new Set(data.tables[0].rows.map((row:any)=>row.uf)).size
 await expect(cities.locator('tbody tr')).toHaveCount(expectedStates)
 const state=cities.locator('tbody tr').first();await state.getByRole('button',{name:/Expandir/}).click()
 await expect(cities.locator('tbody tr.child-row').first()).toBeVisible()
 await expect(cities.locator('tfoot td').nth(1)).toHaveText('1.335')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 const modal=page.getByRole('dialog',{name:'Filtros de formação de cargas'})
 await expect(modal).toBeFocused()
 await expect(modal.getByRole('tab')).toHaveCount(5)
 await page.screenshot({path:'.local/logistica-filtros-modal.png'})
 await modal.getByRole('tab',{name:'Cargas',exact:true}).click()
 await modal.getByLabel('Situação de alocação',{exact:true}).selectOption('partial')
 await modal.getByRole('button',{name:'Cancelar',exact:true}).click()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1.335')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await modal.getByRole('tab',{name:'Cargas',exact:true}).click()
 await expect(modal.getByLabel('Situação de alocação',{exact:true})).toHaveValue('')
 await modal.getByRole('tab',{name:'Período',exact:true}).click()
 await modal.getByLabel('Emissão inicial').fill('2026-09-30');await modal.getByLabel('Emissão final').fill('2026-01-01')
 await modal.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(modal.getByRole('alert')).toBeVisible()
 await modal.getByRole('button',{name:'Cancelar',exact:true}).click()
 await page.waitForFunction(()=>!document.getAnimations().some(a=>a.playState==='running'))
 await page.screenshot({path:'.local/logistica-continuo.png'})
})
