import {test,expect} from '@playwright/test'
test.use({baseURL:'http://127.0.0.1:3002'})
test('planejamento real: cubagem, gráficos, mapa e filtros de destino',async({page,request})=>{
 const errors:string[]=[];page.on('pageerror',error=>errors.push(error.message))
 const response=await request.get('/api/v1/logistica/formacao');expect(response.ok()).toBe(true);const data=await response.json()
 await page.goto('/cargas');await expect(page.locator('[data-metric-id="logistica.cubeLoad"] strong')).toHaveText('2.174,35 m³')
 await expect(page.locator('[data-metric-id="logistica.cubeFree"] strong')).toHaveText('4.553,72 m³')
 const planning=page.getByRole('region',{name:'Planejamento operacional'})
 await planning.scrollIntoViewIfNeeded();await expect(planning).toBeVisible()
 await expect(planning.getByRole('heading',{name:'Previsão de faturamento por mês',exact:true})).toBeVisible()
 await expect(planning.locator('canvas')).toHaveCount(2)
 await expect(planning.getByLabel('Itens por página')).toHaveValue('15')
 await expect(planning.locator('.loading-state')).toHaveCount(0)
 await page.waitForFunction(()=>!document.getAnimations().some(animation=>animation.playState==='running'))
 const forecastFrames=planning.locator('.logistics-chart-grid').first()
 await forecastFrames.scrollIntoViewIfNeeded();await forecastFrames.screenshot({path:'.local/logistica-previsoes.png'})
 const mapFrame=page.locator('[data-series-id="logistica.destinos"]')
 await mapFrame.scrollIntoViewIfNeeded();await expect(mapFrame.locator('canvas')).toBeVisible()
 await page.waitForFunction(()=>!document.getAnimations().some(animation=>animation.playState==='running'))
 await page.locator('.logistics-destinations').screenshot({path:'.local/logistica-mapa-status.png'})
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await page.getByRole('tab',{name:'Localização',exact:true}).click()
 const uf=data.options.ufs.find((value:string)=>/^[A-Z]{2}$/.test(value))
 await page.getByRole('combobox',{name:'Estado (UF)',exact:true}).click()
 await page.getByRole('option',{name:uf,exact:true}).click()
 await page.getByRole('combobox',{name:'Estado (UF)',exact:true}).press('Escape')
 const filtered=await (await request.get('/api/v1/logistica/formacao?uf='+uf)).json()
 await page.getByRole('button',{name:'Aplicar filtros',exact:true}).click()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText(filtered.metrics[0].value.toLocaleString('pt-BR'))
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await page.getByRole('tab',{name:'Localização',exact:true}).click()
 await expect(page.getByRole('button',{name:'Remover '+uf,exact:true})).toBeVisible()
 await page.getByRole('button',{name:'Limpar filtros',exact:true}).click()
 await expect(page.locator('[data-metric-id="logistica.orders"] strong')).toHaveText('1.335')
 await page.getByRole('button',{name:'Filtros',exact:true}).click()
 await page.getByRole('tab',{name:'Localização',exact:true}).click()
 await expect(page.getByRole('button',{name:'Remover '+uf,exact:true})).toHaveCount(0)
 await page.getByRole('button',{name:'Cancelar',exact:true}).click()
 expect(errors).toEqual([])
})
