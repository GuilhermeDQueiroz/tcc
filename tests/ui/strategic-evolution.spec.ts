test('changing strategic dimensions loads only the table and keeps dashboard nodes through errors and stale publications',async({page})=>{
 test.setTimeout(180_000)
 await page.goto('/estrategico')
 await expect(page.locator('.strategic-metrics>.metric-card')).toHaveCount(13,{timeout:60000})
 await expect(page.locator('.loading-state')).toHaveCount(0,{timeout:60000})
 const data=await page.request.get('/api/v1/logistica/estrategico').then(response=>response.json())
 const analysis=page.locator('#strategic-dimensions')
 await page.evaluate(()=>{(window as any).strategicNodes=[...document.querySelectorAll('.strategic-metrics>.metric-card,.strategic-charts canvas')]})
 const unchanged=async()=>expect(await page.evaluate(()=>(window as any).strategicNodes.every((node:Element)=>node.isConnected))).toBe(true)
 const cards=await page.locator('.strategic-metrics').textContent()
 let release!:()=>void
 const pending=new Promise<void>(resolve=>release=resolve)
 await page.route('**/logistica/estrategico?*',async route=>{
  const url=new URL(route.request().url())
  if(url.searchParams.get('section')!=='analysis'){await route.continue();return}
  const response=await route.fetch();await pending;await route.fulfill({response})
 })
 await analysis.getByRole('button',{name:'Cidade',exact:true}).click()
 await expect(analysis.locator('.loading-overlay')).toHaveCount(1)
 await expect(page.locator('.loading-screen')).toHaveCount(0)
 expect(await page.locator('.strategic-metrics').textContent()).toBe(cards)
 await unchanged()
 release()
 await expect(analysis.locator('[data-table-id="strategic.dimensions.CIDADE"]')).toBeVisible({timeout:60000})
 await expect(analysis.locator('.loading-state')).toHaveCount(0,{timeout:60000})
 await unchanged()
 await page.unroute('**/logistica/estrategico?*')
 await page.route('**/logistica/estrategico?*',route=>route.fulfill({status:503,json:{error:'Falha controlada da dimensão'}}))
 await analysis.getByRole('button',{name:'UF',exact:true}).click()
 await expect(analysis.getByRole('alert')).toContainText('Falha controlada')
 await expect(page.locator('.strategic-error')).toHaveCount(0)
 await expect(page.locator('.loading-screen')).toHaveCount(0)
 await unchanged()
 await page.unroute('**/logistica/estrategico?*')
 await analysis.getByRole('button',{name:'Tentar novamente'}).click()
 await expect(analysis.locator('[data-table-id="strategic.dimensions.UF"]')).toBeVisible({timeout:60000})
 await page.route('**/logistica/estrategico?*',route=>route.fulfill({json:{dataVersion:data.dataVersion+'-changed',referenceDate:data.referenceDate,analysis:data.analysis}}))
 await analysis.getByRole('button',{name:'Cidade',exact:true}).click()
 await expect(analysis.getByRole('alert')).toContainText('A publicação mudou')
 expect(await page.locator('.strategic-metrics').textContent()).toBe(cards)
 await unchanged()
})
